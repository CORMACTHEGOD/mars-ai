UNSEEN_FACTS = frozenset({"latency", "recursion", "biodiversity", "asteroid"})

# A handful of original practice words. The model must transform *new*
# strings in validation/test rather than memorize the same word as a lookup.
WORDS = tuple(
    """acorn basil cedar denim ember fern galaxy harbor ivory jasmine kernel
    lantern mango nectar olive pebble quartz ribbon saffron timber umber velvet
    willow xenon yellow zipper amber cobalt delta falcon ginger hazel indigo
    juniper kiwi lemon marble nickel orchid panda rocket silver tulip violet
    wander zephyr cobaltite fernwood lemony piper sunset tamarind willowen
    nebula pebbleton orchidly riverbend solaris velveton windward""".split()
)


@dataclass(frozen=True)
class Example:
    id: str
    prompt: str
    answer: str
    task: str
    family: str
    provenance: str


@dataclass(frozen=True)
class DataPack:
    train: tuple[Example, ...]
    validation: tuple[Example, ...]
    test: tuple[Example, ...]


def normalize_prompt(s: str) -> str:
    normalized = unicodedata.normalize("NFKC", s).casefold()
    return re.sub(r"\s+", " ", normalized).strip(" \t\r\n.,?! ")


def stable_bucket(key: str, seed: int, modulo: int = 10) -> int:
    value = hashlib.sha256(f"{seed}|{key}".encode("utf-8")).digest()
    return int.from_bytes(value[:8], "big") % modulo


def add(examples: list[Example], ident: str, q: str, a: str,
        task: str, family: str, provenance: str) -> None:
    examples.append(Example(ident, q, a, task, family, provenance))


def build_pack(seed: int = 42) -> DataPack:
    train: list[Example] = []
    val: list[Example] = []
    test: list[Example] = []

    # Familiar conversations get new phrasings in validation. The response
    # was seen in training, so this tests wording robustness, not knowledge.
    for i, (question, answer) in enumerate(DIALOGUES):
        family = f"chat:{i}"
        for style, prompt in enumerate((
            question,
            f"Please answer this: {question}",
            f"Mars, {question}",
        )):
            add(train, f"{family}:train:{style}", prompt, answer,
                "chat_known", family, "original_dialogue")
        add(val, f"{family}:paraphrase", f"Could you respond to this: {question}",
            answer, "chat_paraphrase", family, "original_dialogue")

    # Keep certain FACT GROUPS completely absent from training.
    for concept, answer in DEFINITIONS:
        family = f"definition:{concept}"
        if concept in UNSEEN_FACTS:
            add(test, f"{family}:heldout", f"What does {concept} mean?",
                answer, "unseen_fact", family, "original_definition")
            continue
        for i, question in enumerate((
            f"What does {concept} mean?",
            f"Define {concept}.",
            f"Explain {concept} in one sentence.",
        )):
            add(train, f"{family}:train:{i}", question, answer,
                "definition_known", family, "original_definition")
        add(val, f"{family}:paraphrase", f"Could you briefly describe {concept}?",
            answer, "definition_paraphrase", family, "original_definition")

    # Addition pairs are *unordered* groups: 3+8 and 8+3 always belong to
    # the same split, so test operands are not leaked by reversing them.
    for a in range(0, 21):
        for b in range(a, 21):
            family = f"addition:{a}:{b}"
            value = f"{a + b}."
            bucket = stable_bucket(family, seed)
            if bucket >= 8:
                add(test, f"{family}:heldout", f"What is {b} plus {a}?",
                    value, "unseen_addition_pair", family, "computed_arithmetic")
            elif bucket == 7:
                add(val, f"{family}:heldout", f"Calculate {a} + {b}.",
                    value, "validation_addition_pair", family, "computed_arithmetic")
            else:
                for i, question in enumerate((
                    f"What is {a} plus {b}?",
                    f"Calculate {b} + {a}.",
                    f"Add {a} and {b}.",
                )):
                    add(train, f"{family}:train:{i}", question, value,
                        "addition_train", family, "computed_arithmetic")

    # Whole input words, not just prompt strings, are held out. Both
    # transformations belong to the same family/split for a given word.
    for word in WORDS:
        family = f"word:{word}"
        bucket = stable_bucket(family, seed)
        target = test if bucket >= 8 else val if bucket == 7 else train
        for operation, instruction, answer in (
            ("reverse", f"Reverse the letters in {word}.", word[::-1]),
            ("uppercase", f"Write {word} in capitals.", word.upper()),
        ):
            add(target, f"{family}:{operation}", instruction, answer,
                "word_transform", family, "computed_text_rule")

    rng = random.Random(seed)
    for data in (train, val, test):
        rng.shuffle(data)
    pack = DataPack(tuple(train), tuple(val), tuple(test))
    verify_pack(pack)
    return pack


def verify_pack(pack: DataPack, *, max_context_bytes: int = 160) -> None:
    """Fail closed on duplicates, contradictory labels, invalid splits or PII."""
    if not pack.train or not pack.validation or not pack.test:
        raise ValueError("Each dataset split must contain examples")
    all_examples = pack.train + pack.validation + pack.test
    ids = [e.id for e in all_examples]
    if len(ids) != len(set(ids)):
        raise ValueError("Duplicate example IDs")
    questions = {}
    for example in all_examples:
        if not example.prompt.strip() or not example.answer.strip():
            raise ValueError("Empty question or answer")
        prompt = normalize_prompt(example.prompt)
        if prompt in questions:
            raise ValueError(f"Repeated/colliding prompt: {example.prompt}")
        questions[prompt] = example.answer
        if re.search(r"https?://|[\w.+-]+@[\w.-]+\.[a-z]{2,}", example.prompt + example.answer, re.I):
            raise ValueError(f"Potential external URL or email: {example.id}")
        length = len((f"User: {example.prompt}\nMars: {example.answer}\n").encode("utf-8"))
        if length - 1 > max_context_bytes:
            raise ValueError(f"Example exceeds {max_context_bytes}-byte model context: {example.id}")

    def families(items: tuple[Example, ...], prefix: str) -> set[str]:
        return {e.family for e in items if e.family.startswith(prefix)}

    # We intentionally ALLOW the same facts in training/validation (new
    # wording), but never allow held-out fact CONCEPTS in training.
    assert not (families(pack.train, "definition:") & families(pack.test, "definition:"))
    # For compositional tasks, entire input families must be disjoint.
    for family_prefix in ("addition:", "word:"):
        tr = families(pack.train, family_prefix)
        va = families(pack.validation, family_prefix)
        te = families(pack.test, family_prefix)
        if tr & va or tr & te or va & te:
            raise ValueError(f"Cross-split family leakage: {family_prefix}")
    for e in pack.test:
        if e.task == "unseen_fact":
            assert e.family not in {t.family for t in pack.train}


def counts(examples: tuple[Example, ...]) -> dict[str, int]:
    return dict(sorted(Counter(e.task for e in examples).items()))


def manifest(pack: DataPack) -> dict:
    data = {
        "dataset": "mars-data-v3",
        "seed": 42,
        "max_context_bytes": 160,
        "version": "research-1",
        "provenance": "Original short facts and dialogues; local deterministic arithmetic and text rules",
        "limitations": [
            "Not a large corpus; does not teach general-purpose language competence.",
            "Paraphrase validation shares answers with training and tests wording, not novel facts.",
            "Held-out arithmetic pairs are grouped by unordered operands to avoid reversal leakage.",
            "Held-out concept tests cannot show that a model knows unseen facts.",
            "All evaluations are visible in a public repository; this is not a secret benchmark.",
        ],
        "splits": {
            "train": {"rows": len(pack.train), "tasks": counts(pack.train)},
            "validation": {"rows": len(pack.validation), "tasks": counts(pack.validation)},
            "test": {"rows": len(pack.test), "tasks": counts(pack.test)},
        },
    }
    for name in ("train", "validation", "test"):
        items = getattr(pack, name)
        payload = "\n".join(json.dumps(asdict(e), sort_keys=True) for e in items)
        data["splits"][name]["sha256"] = hashlib.sha256(payload.encode("utf-8")).hexdigest()
    return data


def write_pack(output_dir: Path, pack: DataPack) -> dict:
    verify_pack(pack)
    output_dir.mkdir(parents=True, exist_ok=True)
    for name in ("train", "validation", "test"):
        lines = [json.dumps(asdict(e), ensure_ascii=False) for e in getattr(pack, name)]
        (output_dir / f"{name}.jsonl").write_text("\n".join(lines) + "\n", encoding="utf-8")
    details = manifest(pack)
    (output_dir / "manifest.json").write_text(json.dumps(details, indent=2) + "\n", encoding="utf-8")
    return details


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate and validate original Mars data V3")
    parser.add_argument("--output", default="artifacts/mars-data-v3")
    args = parser.parse_args()
    pack = build_pack()
    data = write_pack(Path(args.output), pack)
    for name, stats in data["splits"].items():
        print(f"{name}: {stats['rows']} examples | {stats['tasks']}", flush=True)
    print(f"Wrote validated data to {args.output}", flush=True)


if __name__ == "__main__":
    main()
