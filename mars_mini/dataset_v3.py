"""Mars data pack V3: original, auditable examples with leakage-aware splits.

NO model training, pretrained weights, API calls, scraping, or personal data.
This pack is separate from the live Mars-1 and Mars-2 weights. It is meant
for studying generalization, not claiming a capable chatbot.

All sentence templates and factual definitions are authored for this project.
Arithmetic and word-transform answers are generated by explicit local rules.
"""
